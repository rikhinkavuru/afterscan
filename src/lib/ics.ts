import type { DatedStep } from "./dates";

const pad = (n: number) => String(n).padStart(2, "0");
const icsDate = (d: Date) => `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}`;
const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/;/g, "\;").replace(/,/g, "\\,").replace(/\r?\n/g, "\\n");

/** Fold long lines per RFC 5545 (75 octets). */
function fold(line: string): string {
  const out: string[] = [];
  let cur = line;
  while (cur.length > 73) {
    out.push(cur.slice(0, 73));
    cur = " " + cur.slice(73);
  }
  out.push(cur);
  return out.join("\r\n");
}

export interface IcsEvent {
  uid: string;
  date: Date; // all-day
  summary: string;
  description: string;
  alarmDaysBefore?: number;
}

export function buildIcs(events: IcsEvent[], calName = "Afterscan follow-up"): string {
  const now = new Date();
  const stamp = `${icsDate(now)}T${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}00Z`;
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Afterscan//Follow-up plan//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    `X-WR-CALNAME:${esc(calName)}`,
  ];
  for (const e of events) {
    const next = new Date(e.date);
    next.setDate(next.getDate() + 1);
    lines.push(
      "BEGIN:VEVENT",
      `UID:${e.uid}`,
      `DTSTAMP:${stamp}`,
      `DTSTART;VALUE=DATE:${icsDate(e.date)}`,
      `DTEND;VALUE=DATE:${icsDate(next)}`,
      `SUMMARY:${esc(e.summary)}`,
      `DESCRIPTION:${esc(e.description)}`,
    );
    if (e.alarmDaysBefore) {
      lines.push("BEGIN:VALARM", "ACTION:DISPLAY", `DESCRIPTION:${esc(e.summary)}`, `TRIGGER:-P${e.alarmDaysBefore}D`, "END:VALARM");
    }
    lines.push("END:VEVENT");
  }
  lines.push("END:VCALENDAR");
  return lines.map(fold).join("\r\n") + "\r\n";
}

export function stepsToEvents(steps: DatedStep[], labelFor: (findingId: string) => string, guidelineFor: (findingId: string) => string): IcsEvent[] {
  return steps.map((s, i) => ({
    uid: `afterscan-${s.findingId}-${i}-${s.fromISO}@afterscan`,
    date: s.from,
    summary: `${s.optional ? "Consider: " : ""}${s.what} (${labelFor(s.findingId)})`,
    description: [
      `Follow-up window: ${s.fromISO}${s.fromISO !== s.toISO ? ` to ${s.toISO}` : ""}.`,
      s.condition ? `Condition: ${s.condition}.` : "",
      `Source: ${guidelineFor(s.findingId)}.`,
      "Generated by Afterscan from a published guideline. Confirm with your doctor; this is not medical advice.",
    ]
      .filter(Boolean)
      .join("\n"),
    alarmDaysBefore: 14,
  }));
}
